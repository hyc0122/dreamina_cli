export function schemeNumberContinuityRules(): string {
  return `主线数字连续性规则：
1. 这里的数字不是装饰数字，也不是账单展示，只用于锁定剧本/小说里的主线数字状态，防止剧情断裂。
2. 轻量方案阶段只锁定会影响后续连续性的关键变量：订单、合同、证据编号、时间点、年龄、期限、资源名额、明显会改变关系走向的金额或数量。不要写流水账，不要堆无关数字。
3. 凡是会推动冲突的金额、资源数量、合同额度、工资、欠款、彩礼、医药费、学费、灵石、名额、股份、日期、年龄、期限，都必须有单位、来源和剧情功能。
4. 不承担剧情功能的数字不要硬写；承担剧情功能的数字不能模糊成“很多钱、一大笔、好几万、不少资源”。`;
}

export function hiddenPlanNumberContinuityRules(): string {
  return `内部主线数字账本：
1. 必须在隐藏故事结构里建立内部主线数字账本，只供系统续写和自检使用，不得输出给用户。
2. 账本只追踪会影响剧情的关键数字：订单、合同、证据编号、时间点、年龄、期限、资源名额，以及必要时才出现的金额或数量。
3. 每个关键数字都要记录来源、当前归属、是否已消耗、能否继续使用、下一次变化条件。
4. 账本用于保证上一集结尾和下一集开头的数字/状态一致；不能让角色从无来源状态突然获得巨额数字变化、身份变化、资源变化或权力变化。
5. 最终小说/剧本不展示账本，只在剧情需要时通过合同、票据、转账记录、口供、库存、工资条、借条、房本、订单、宗门令牌等可见道具露出关键数字。`;
}

export function episodeNumberContinuityRules(hasPreviousEpisode: boolean): string {
  return `逐集主线数字规则：
1. 写作前先内部核对隐藏账本和${hasPreviousEpisode ? '上一集最终内容' : '第一集初始设定'}，本集开头的订单、合同、证据编号、期限、年龄/时间线和必要金额必须承接既有状态。
2. 本集只能改变有剧情功能的关键数字；每次变化必须有可见原因，例如收到定金、签下订单、借款、抵押、变卖、赔偿、扣款、奖励、偷换证据、资源消耗或期限推进。
3. 禁止无来源跃迁：上一集没有相关状态，下一集不能突然跳出不合逻辑的关键数字变化，除非本集明确写出来源、代价和证据。
4. 禁止为了显得真实而塞无关数字。数字只服务冲突、证据、时间压力、状态变化和人物选择。
5. 最终成品可以写关键合同金额、工资、欠款、资产、期限等必要数字，但不要输出内部账本、计算过程、流水账或“我来算一下”式说明。`;
}

export function selfCheckNumberContinuityRules(): string {
  return `关键数字自检：
1. 必须区分关键数字和无关数字。关键数字包括订单合同、债务收入、资产股份、工资物价、彩礼嫁妆、医药费学费、灵石功法、年龄日期、期限和证据编号。
2. 关键数字缺失、单位缺失、来源缺失、消耗不明、时代/世界观价值不匹配、上一集到本集状态跳跃，都必须判为故事结构或人物逻辑问题。
3. 无关数字堆砌、账单流水、把内部账本写给用户，也必须扣分，因为它会伤害小说/剧本成品感。
4. 修复只能补关键数字的来源、单位、代价、道具证据或前后承接；不要把整集改成财务报表，不要为修数字重写全篇。`;
}
